import os
from reportlab.lib.pagesizes import A4, mm
from reportlab.pdfgen import canvas
from reportlab.lib.colors import HexColor, black, white, gray


def generate_cr80_pdf(front_path, back_path, output):
    """
    Generates a 2-page PDF in standard CR80 vertical badge size (54mm x 86mm).
    Page 1: Front
    Page 2: Back
    """
    card_width = 54 * mm
    card_height = 86 * mm

    c = canvas.Canvas(output, pagesize=(card_width, card_height))

    # Page 1: Front
    if os.path.exists(front_path):
        c.drawImage(front_path, 0, 0, width=card_width, height=card_height)
    c.showPage()

    # Page 2: Back
    if os.path.exists(back_path):
        c.drawImage(back_path, 0, 0, width=card_width, height=card_height)
    c.showPage()

    c.save()


def generate_a4_single_card_pdf(front_path, back_path, title, output):
    """
    Generates an A4 sheet (210mm x 297mm) containing both Front and Back
    side-by-side with cutting guides, fold lines, and printing guidelines.
    """
    page_w, page_h = A4
    card_w = 54 * mm
    card_h = 86 * mm

    c = canvas.Canvas(output, pagesize=A4)

    # Header branding
    c.setFillColor(HexColor('#002B49'))
    c.setFont('Helvetica-Bold', 18)
    c.drawCentredString(page_w / 2, page_h - 35 * mm, "NIELIT - Official ID Card")

    c.setFont('Helvetica', 11)
    c.setFillColor(HexColor('#555555'))
    c.drawCentredString(page_w / 2, page_h - 43 * mm, f"Card Holder: {title}")

    # Instructions box
    c.setStrokeColor(HexColor('#D0D7DE'))
    c.setFillColor(HexColor('#F6F8FA'))
    c.roundRect(30 * mm, page_h - 70 * mm, page_w - 60 * mm, 18 * mm, 3 * mm, stroke=1, fill=1)

    c.setFillColor(HexColor('#24292F'))
    c.setFont('Helvetica-Bold', 9)
    c.drawString(35 * mm, page_h - 59 * mm, "Printing Instructions:")
    c.setFont('Helvetica', 8.5)
    c.drawString(35 * mm, page_h - 64 * mm, "1. Print at 100% scale (Do NOT select 'Fit to Page' or 'Shrink').")
    c.drawString(35 * mm, page_h - 68 * mm, "2. Cut along outer solid lines. Fold along center dotted line and insert into badge holder or laminate.")

    # Calculate placement for Front and Back side-by-side
    gap = 8 * mm
    total_w = (card_w * 2) + gap
    start_x = (page_w - total_w) / 2
    y_pos = page_h - 170 * mm

    # Labels
    c.setFont('Helvetica-Bold', 10)
    c.setFillColor(HexColor('#333333'))
    c.drawCentredString(start_x + (card_w / 2), y_pos + card_h + 3 * mm, "FRONT")
    c.drawCentredString(start_x + card_w + gap + (card_w / 2), y_pos + card_h + 3 * mm, "BACK")

    # Front Card
    if os.path.exists(front_path):
        c.drawImage(front_path, start_x, y_pos, width=card_w, height=card_h)
        # Cutting border
        c.setStrokeColor(HexColor('#999999'))
        c.setLineWidth(0.5)
        c.rect(start_x, y_pos, card_w, card_h)

    # Back Card
    back_x = start_x + card_w + gap
    if os.path.exists(back_path):
        c.drawImage(back_path, back_x, y_pos, width=card_w, height=card_h)
        # Cutting border
        c.setStrokeColor(HexColor('#999999'))
        c.setLineWidth(0.5)
        c.rect(back_x, y_pos, card_w, card_h)

    # Center fold line
    c.setStrokeColor(HexColor('#888888'))
    c.setDash([2, 3], 0)
    center_x = start_x + card_w + (gap / 2)
    c.line(center_x, y_pos - 10 * mm, center_x, y_pos + card_h + 10 * mm)
    c.setDash([], 0)

    # Footer
    c.setFont('Helvetica', 8)
    c.setFillColor(HexColor('#888888'))
    c.drawCentredString(page_w / 2, 20 * mm, "Generated by Lovnish - NIELIT ID Card System | Verified Document")

    c.showPage()
    c.save()


def generate_bulk_a4_pdf(card_pairs, output, back_first=True):
    """
    card_pairs: list of dicts with {'front': path, 'back': path, 'title': str}
    Lays out cards in an exact 3-column table grid on A4 (3 columns x 2 rows = 6 card faces per page),
    matching the NIELIT export format:
      Row 0: [Card 1 Back, Card 1 Front, Card 2 Back]
      Row 1: [Card 2 Front, Card 3 Back, Card 3 Front]
    """
    page_w, page_h = A4
    card_w = 54 * mm
    card_h = 86 * mm

    # 3 symmetric columns
    col_x = [14 * mm, 78 * mm, 142 * mm]
    # 2 rows per page with clean cutting margins
    row_y = [page_h - 115 * mm, page_h - 225 * mm]

    # Flatten into sequential images (Back, Front by default)
    items = []
    for pair in card_pairs:
        front = pair.get('front')
        back = pair.get('back')
        title = pair.get('title', '')
        if back_first:
            if back and os.path.exists(back):
                items.append({'path': back, 'label': f"{title} (Back)"})
            if front and os.path.exists(front):
                items.append({'path': front, 'label': f"{title} (Front)"})
        else:
            if front and os.path.exists(front):
                items.append({'path': front, 'label': f"{title} (Front)"})
            if back and os.path.exists(back):
                items.append({'path': back, 'label': f"{title} (Back)"})

    if not items:
        return

    c = canvas.Canvas(output, pagesize=A4)
    total_items = len(items)
    idx = 0

    while idx < total_items:
        # Header on each page
        c.setFillColor(HexColor('#002B49'))
        c.setFont('Helvetica-Bold', 15)
        c.drawCentredString(page_w / 2, page_h - 15 * mm, "NIELIT ID Cards - 3-Column Batch Sheet")
        c.setFont('Helvetica', 8)
        c.setFillColor(HexColor('#666666'))
        c.drawCentredString(page_w / 2, page_h - 20 * mm, "Print at 100% scale (A4). Cut along borders.")

        for r in range(2):
            for col in range(3):
                if idx >= total_items:
                    break

                item = items[idx]
                img_path = item['path']
                x = col_x[col]
                y = row_y[r]

                # Draw Card Image
                c.drawImage(img_path, x, y, width=card_w, height=card_h)

                # Outer cutting/table border
                c.setStrokeColor(HexColor('#777777'))
                c.setLineWidth(0.5)
                c.rect(x, y, card_w, card_h)

                idx += 1

        c.showPage()

    c.save()
